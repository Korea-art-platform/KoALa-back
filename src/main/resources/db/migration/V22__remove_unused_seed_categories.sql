-- ============================================================
-- V22: 쓰지 않는 소분류 초기 데이터 제거
-- ============================================================
--
-- V21 이 옛 SkuGenre enum 8개를 그대로 소분류로 옮겨 심었다. 그중 실제로 쓰이는 것은
-- SCULPTURE, ART_TOY 뿐이고 나머지는 한 번도 상품에 붙은 적이 없다.
-- 쓰지 않는 선택지가 드롭다운에 남아 있으면 등록할 때마다 고르는 손이 느려진다.
-- 앞으로는 어드민에서 직접 등록한 것만 쓴다.
--
-- V21 을 고치지 않고 새 파일로 지우는 이유:
-- V21 은 이미 운영에 적용되어 체크섬이 기록돼 있다. 내용을 바꾸면 Flyway 가
-- validate 단계에서 기동을 거부한다. 적용된 마이그레이션은 손대지 않는다.

-- 상품이 쓰고 있으면 절대 지우지 않는다.
-- 지워 버리면 그 상품은 드롭다운에도, 메인 페이지 어느 섹션에도 걸리지 않는 미아가 된다.
-- (지금은 해당 없지만, 이 스크립트가 다른 환경에서 돌 때를 위한 안전장치다)
DELETE FROM sku_categories
WHERE type = 'SUB'
  AND code IN ('PAINTING', 'PRINT', 'PHOTOGRAPH', 'INSTALLATION', 'TEXTILE', 'OTHER')
  AND code NOT IN (
      SELECT DISTINCT genre FROM skus WHERE genre IS NOT NULL
  );
